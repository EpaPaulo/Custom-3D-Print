export const niche = (id) => NICHES.find((n) => n.id === id) || null;
export const product = (handle) => PRODUCTS.find((p) => p.handle === handle) || null;
export const byNiche = (id) => PRODUCTS.filter((p) => p.niche === id);
export const personalisable = () => PRODUCTS.filter((p) => p.customizer);
export const featured = () => PRODUCTS.filter((p) => p.featured);

/** How many products each niche holds — the home page prints it on the card. */
export const nicheCount = (id) => byNiche(id).length;

/** Free-text search over what a shopper would actually type. */
export function search(term) {
  const q = String(term || '').trim().toLowerCase();
  if (!q) return [];
  const words = q.split(/\s+/);
  return PRODUCTS.filter((p) => {
    const hay = [p.title, p.subtitle, p.blurb, niche(p.niche).title].join(' ').toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}

/** Anything else from the same niche — the "quem viu isto" row. */
export function related(handle, limit = 4) {
  const p = product(handle);
  if (!p) return [];
  return byNiche(p.niche).filter((x) => x.handle !== handle).slice(0, limit);
}
